const T2S: ReadonlyMap<string, string> = (() => {
  const map = new Map<string, string>();
  const duplicates: string[] = [];

  T2S_ROWS.forEach(([tradRow, simpRow], rowIndex) => {
    const trad = [...tradRow];
    const simp = [...simpRow];
    if (trad.length !== simp.length) {
      throw new Error(
        `繁简对照表第 ${rowIndex + 1} 行长度不一致：繁体 ${trad.length} 字，简体 ${simp.length} 字\n繁：${tradRow}\n简：${simpRow}`,
      );
    }
    for (let i = 0; i < trad.length; i += 1) {
      const t = trad[i];
      const s = simp[i];
      if (t === undefined || s === undefined) continue;
      if (t === s) {
        throw new Error(`繁简对照表第 ${rowIndex + 1} 行出现繁简同字「${t}」，属于无效条目，请删除`);
      }
      if (map.has(t)) {
        duplicates.push(`「${t}」在第 ${rowIndex + 1} 行重复`);
        continue;
      }
      map.set(t, s);
    }
  });

  if (duplicates.length > 0) {
    throw new Error(`繁简对照表存在重复繁体字：\n${duplicates.join('\n')}`);
  }
  return map;
})();

/** 对照表条目数（供测试与自检使用）。 */
export const T2S_SIZE = T2S.size;

/** 所有简体目标字，用于判断某个字是否已经是简体。 */
const SIMPLIFIED_TARGETS: ReadonlySet<string> = new Set(T2S.values());

/**
 * 把繁体文本转成简体。
 *
 * 未收录的字原样保留 —— 宁可保留繁体，也不做无依据的猜测替换。
 */
export function toSimplified(input: string): string {
  let out = '';
  for (const char of input) {
    out += T2S.get(char) ?? char;
  }
  return out;
}

/** 常见繁体部件所在的 Unicode 区段。 */
const SUSPECT_TRADITIONAL_RE =
  /[\u8a00-\u8bff\u8c9d-\u8cff\u8eca-\u8eff\u99ac\u9ce5\u9b5a\u7cf8\u91d1\u9580\u98df\u98a8\u9801\u898b\u97cb\u9f52\u9f8d\u9f9c]/u;

/**
 * 繁简同形字白名单。
 *
 * 这些字虽然占用了繁体部件的码位，但在简体中文里就是这么写，
 * 不需要也不应被转换。列出来是为了让数据自检不产生误报。
 */
const SIMPLIFIED_SAME_SHAPE: ReadonlySet<string> = new Set([
  ...'言金食誓詹辯辨辦凡凶兌兔兒黨鬥鬧鹹鹼鹽鼓齊齒龍龜',
]);

/**
 * 找出文本中「看起来是繁体但对照表没覆盖」的字符，用于数据自检。
 *
 * 判据：落在常见繁体部件区（言/貝/車/糸/金/門/食/風/頁/見/馬/鳥/魚/龍/齒/龜…），
 * 且既不在对照表的繁体侧、也不是对照表的简体目标字、也不在繁简同形白名单里。
 *
 * 这是保守估计：宁可多报让作者复核，也不要漏掉真正没转换的繁体字。
 */
export function findUnknownTraditional(input: string): string[] {
  const hits = new Set<string>();
  for (const char of input) {
    if (T2S.has(char)) continue;
    if (SIMPLIFIED_TARGETS.has(char)) continue;
    if (SIMPLIFIED_SAME_SHAPE.has(char)) continue;
    if (SUSPECT_TRADITIONAL_RE.test(char)) hits.add(char);
  }
  return [...hits];
}

/** 去掉所有标点、空白与全角符号，只留汉字、字母、数字。用于宽松比对。 */
export function normalizeForCompare(input: string): string {
  return input.replace(/[^\p{Script=Han}\p{L}\p{N}]/gu, '');
}

/** 按中英文句读切句，返回不含标点的句子片段。 */
export function splitClauses(input: string): string[] {
  return input
    .split(/[，。；！？、：,.;!?:]|\s+/u)
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
}

/** Levenshtein 编辑距离（用于校对时容忍个别异体字差异）。 */
export function editDistance(a: string, b: string): number {
  if (a === b) return 0;
  if (a.length === 0) return b.length;
  if (b.length === 0) return a.length;

  let prev: number[] = Array.from({ length: b.length + 1 }, (_, i) => i);
  const curr: number[] = new Array<number>(b.length + 1);

  for (let i = 1; i <= a.length; i += 1) {
    curr[0] = i;
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      curr[j] = Math.min(
        (curr[j - 1] ?? 0) + 1,
        (prev[j] ?? 0) + 1,
        (prev[j - 1] ?? 0) + cost,
      );
    }
    prev = [...curr];
  }
  return prev[b.length] ?? 0;
}
